    private fun choose(arr: Array<String>, rnd: Random, recent: ArrayDeque<String>): String {
        var t = arr[rnd.nextInt(arr.size)]
        var tries = 0
        while (recent.contains(t) && tries < 14) {
            t = arr[rnd.nextInt(arr.size)]
            tries++
        }
        recent.addLast(t)
        while (recent.size > 34) recent.removeFirst()
        return t
    }

    fun pick(name: String, rnd: Random, recent: ArrayDeque<String>): String {
        val arr = byName[name] ?: system
        return choose(arr, rnd, recent)
    }

